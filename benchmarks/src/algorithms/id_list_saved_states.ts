import type { SavedIdList } from "articulated";
import { IdList } from "articulated";
import {
  BunchIndexSavedIdListMessage,
  ClientIndexSavedIdListMessage,
} from "../generated/id_list_saved_state";
import { IdListAlgorithm, IdListAlgorithmBase } from "./id_list";

/*
 * Alternative saved state formats for IdList.
 *
 * Each algorithm post-processes IdList.save() into its own format, and converts
 * back to a SavedIdList before calling IdList.load().
 *
 * "Signed count" means that isDeleted & count are combined into one number,
 * with negative counts indicating deleted ids.
 *
 * Protobuf code in src/generated/ is built from id_list_saved_state.proto using `pnpm proto`.
 */

type SavedIdListItem = SavedIdList[number];

function signedCount(item: SavedIdListItem): number {
  return item.isDeleted ? -item.count : item.count;
}

function unsignedItem(
  bunchId: string,
  startCounter: number,
  signedCount: number,
): SavedIdListItem {
  return signedCount < 0
    ? { bunchId, startCounter, count: -signedCount, isDeleted: true }
    : { bunchId, startCounter, count: signedCount, isDeleted: false };
}

/**
 * Splits a bunchId of the form `"clientId_seqNum"` (seqNum base-36 encoded),
 * as generated by IdListAlgorithm.
 */
function splitBunchId(bunchId: string): [clientId: string, seqNum: number] {
  const underscore = bunchId.lastIndexOf("_");
  return [
    bunchId.slice(0, underscore),
    parseInt(bunchId.slice(underscore + 1), 36),
  ];
}

function joinBunchId(clientId: string, seqNum: number): string {
  return `${clientId}_${seqNum.toString(36)}`;
}

// --- Formats 1-3: Keep bunchIds intact. ---

type SignedSavedState = Array<{
  bunchId: string;
  startCounter: number;
  count: number;
}>;

/**
 * Format 1: SavedIdList with signed counts.
 */
export class IdListSignedAlgorithm extends IdListAlgorithm {
  save(): string {
    const saved = this.list.save();
    const out: SignedSavedState = new Array(saved.length);
    for (let i = 0; i < saved.length; i++) {
      const item = saved[i];
      out[i] = {
        bunchId: item.bunchId,
        startCounter: item.startCounter,
        count: signedCount(item),
      };
    }
    return JSON.stringify(out);
  }

  load(savedState: string): void {
    const parsed = JSON.parse(savedState) as SignedSavedState;
    const saved: SavedIdList = new Array(parsed.length);
    for (let i = 0; i < parsed.length; i++) {
      const item = parsed[i];
      saved[i] = unsignedItem(item.bunchId, item.startCounter, item.count);
    }
    this.list = IdList.load(saved);
  }
}

type TransposedSavedState = {
  bunchIds: string[];
  startCounters: number[];
  counts: number[];
};

/**
 * Format 2: Format 1, transposed (object of arrays).
 */
export class IdListTransposedAlgorithm extends IdListAlgorithm {
  save(): string {
    const saved = this.list.save();
    const out: TransposedSavedState = {
      bunchIds: new Array(saved.length),
      startCounters: new Array(saved.length),
      counts: new Array(saved.length),
    };
    for (let i = 0; i < saved.length; i++) {
      const item = saved[i];
      out.bunchIds[i] = item.bunchId;
      out.startCounters[i] = item.startCounter;
      out.counts[i] = signedCount(item);
    }
    return JSON.stringify(out);
  }

  load(savedState: string): void {
    const { bunchIds, startCounters, counts } = JSON.parse(
      savedState,
    ) as TransposedSavedState;
    const saved: SavedIdList = new Array(bunchIds.length);
    for (let i = 0; i < bunchIds.length; i++) {
      saved[i] = unsignedItem(bunchIds[i], startCounters[i], counts[i]);
    }
    this.list = IdList.load(saved);
  }
}

type BunchIndexSavedState = {
  /** Distinct bunchIds. */
  bunchIds: string[];
  /** Indices into bunchIds. */
  bunchIndices: number[];
  startCounters: number[];
  counts: number[];
};

function toBunchIndex(saved: SavedIdList): BunchIndexSavedState {
  const bunchIndexMap = new Map<string, number>();
  const out: BunchIndexSavedState = {
    bunchIds: [],
    bunchIndices: new Array(saved.length),
    startCounters: new Array(saved.length),
    counts: new Array(saved.length),
  };
  for (let i = 0; i < saved.length; i++) {
    const item = saved[i];
    let bunchIndex = bunchIndexMap.get(item.bunchId);
    if (bunchIndex === undefined) {
      bunchIndex = out.bunchIds.length;
      out.bunchIds.push(item.bunchId);
      bunchIndexMap.set(item.bunchId, bunchIndex);
    }
    out.bunchIndices[i] = bunchIndex;
    out.startCounters[i] = item.startCounter;
    out.counts[i] = signedCount(item);
  }
  return out;
}

function fromBunchIndex({
  bunchIds,
  bunchIndices,
  startCounters,
  counts,
}: BunchIndexSavedState): SavedIdList {
  const saved: SavedIdList = new Array(bunchIndices.length);
  for (let i = 0; i < bunchIndices.length; i++) {
    saved[i] = unsignedItem(
      bunchIds[bunchIndices[i]],
      startCounters[i],
      counts[i],
    );
  }
  return saved;
}

/**
 * Format 3: Format 2, with distinct bunchIds extracted into a single array
 * and referenced by index.
 */
export class IdListBunchIndexAlgorithm extends IdListAlgorithm {
  save(): string {
    return JSON.stringify(toBunchIndex(this.list.save()));
  }

  load(savedState: string): void {
    this.list = IdList.load(fromBunchIndex(JSON.parse(savedState)));
  }
}

// --- Formats 4-7 & 9: Split bunchIds into clientId and seqNum. ---

type SplitSavedState = Array<{
  clientId: string;
  seqNum: number;
  startCounter: number;
  count: number;
  isDeleted: boolean;
}>;

function toSplit(saved: SavedIdList): SplitSavedState {
  const out: SplitSavedState = new Array(saved.length);
  for (let i = 0; i < saved.length; i++) {
    const item = saved[i];
    const [clientId, seqNum] = splitBunchId(item.bunchId);
    out[i] = {
      clientId,
      seqNum,
      startCounter: item.startCounter,
      count: item.count,
      isDeleted: item.isDeleted,
    };
  }
  return out;
}

function fromSplit(split: SplitSavedState): SavedIdList {
  const saved: SavedIdList = new Array(split.length);
  for (let i = 0; i < split.length; i++) {
    const item = split[i];
    saved[i] = {
      bunchId: joinBunchId(item.clientId, item.seqNum),
      startCounter: item.startCounter,
      count: item.count,
      isDeleted: item.isDeleted,
    };
  }
  return saved;
}

/**
 * Format 4: SavedIdList with bunchIds split into clientId and seqNum.
 */
export class IdListSplitAlgorithm extends IdListAlgorithm {
  save(): string {
    return JSON.stringify(toSplit(this.list.save()));
  }

  load(savedState: string): void {
    this.list = IdList.load(fromSplit(JSON.parse(savedState)));
  }
}

